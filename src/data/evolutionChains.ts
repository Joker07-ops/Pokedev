const EVOLUTION_MAP: Record<string, string[]> = {};

for (const chain of chains) {
  const clean = chain.map((n) => n.trim().toLowerCase());
  for (const name of clean) {
    if (!EVOLUTION_MAP[name]) {
      EVOLUTION_MAP[name] = clean;
    }
  }
}

export function getEvolutionChain(name: string): string[] | null {
  return EVOLUTION_MAP[name.toLowerCase()] ?? null;
}
